public class Whileloop_ex {
    public static void main(String[] args) {
     int i=1;
     while(i <= 5){
        System.out.println(i);
        i++;
     }  
     int a = 1;
     while(a <= 100){
        if(a % 2 == 0){
            System.out.println(a);
            
        }
        a++;
     } 
}

}